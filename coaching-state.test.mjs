function hopCount(hops) {
  const seen = new Set();
  const walk = (height, sequence) => {
    if (sequence.length === hops) { if (height === 0) seen.add(sequence.join('')); return; }
    walk(height+1, sequence.concat('U'));
    if (height-1 >= 0) walk(height-1, sequence.concat('D'));
  };
  walk(0, []);
  return seen.size;
}
